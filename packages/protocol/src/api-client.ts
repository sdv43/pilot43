import type {
  AppSettings,
  Chat,
  ChatSettings,
  FollowupAnswer,
  GeneratedFile,
  McpServer,
  MessageRun,
  MessageUser,
  ModelProviderModel,
  ModelRunSettings,
  ModelTool,
  OllamaModelProvider,
  OpenAIModelProvider,
  OpenRouterModelProvider,
  PageContent,
  PageContentSelection,
  Prompt,
  Workspace,
} from "./entities"
import type { ApiNotificationSource } from "./notifications"

/**
 * Result of {@link BackendApi.chatMessageSend}. `chatId` is the chat the
 * message was added to, which is newly created when an empty chat id was sent.
 */
export interface ChatMessageSendResult {
  chatId: Chat["id"]
  userMessage: MessageUser
}

export interface ModelProviderCheckResult {
  success: boolean
  message: string
  /** Provider-local names of the models the provider reported. */
  models?: string[]
  /** Time the model list request took, in milliseconds. */
  latencyMs?: number
}

type Providers =
  OllamaModelProvider | OpenAIModelProvider | OpenRouterModelProvider

/**
 * Operations served by the agent backend: workspaces, chats, message runs,
 * model providers, tools, MCP servers, commands and app settings.
 */
export interface BackendApi {
  appSettingsGet(): Promise<AppSettings>
  appSettingsUpdate(settings: AppSettings): Promise<AppSettings>

  workspaceGet(): Promise<Workspace[]>
  workspaceCreate(
    workspace: Partial<Omit<Workspace, "id" | "lastSelectedChatId" | "name">> &
      Pick<Workspace, "name">,
  ): Promise<Workspace>
  workspaceUpdate(workspace: Workspace): Promise<Workspace>
  workspaceDelete(workspaceId: Workspace["id"]): Promise<void>

  chatGetByWorkspace(workspaceId: Workspace["id"]): Promise<Chat[]>
  chatDelete(chatId: Chat["id"]): Promise<void>

  chatMessageSend(
    chatId: Chat["id"],
    message: Pick<
      MessageUser,
      "attachmentReferences" | "attachments" | "commandReference" | "content"
    >,
    model: Pick<ModelProviderModel, "name" | "providerId">,
    workspaceId: Workspace["id"],
    initialSettings?: ChatSettings,
    modelSettings?: ModelRunSettings,
  ): Promise<ChatMessageSendResult>

  /**
   * The chatTokenEstimateGet method estimates the number of tokens going to be used for the next potential message.
   * The estimate is based on the provider-reported prompt tokens of the last measured user message,
   * plus the tokens of assistant messages produced after it.
   */
  chatTokenEstimateGet(chatId?: Chat["id"] | null): Promise<null | number>

  chatMessageRunGet(chatId: Chat["id"]): Promise<MessageRun[]>
  chatMessageRunRetry(id: MessageRun["id"]): Promise<void>
  chatMessageRunStop(id: MessageRun["id"]): Promise<void>
  chatMessageRunDelete(id: MessageRun["id"]): Promise<void>
  chatMessageRunDeleteAfter(id: MessageRun["id"]): Promise<void>

  /**
   * Submits the user's answer to a prompt that paused generation — a
   * follow-up question (see `ask_followup_question`), a continuation notice or
   * a tool approval (see `toolApprovalAnswers`). Resumes the message run's
   * generation. `answers` carries the structured answers of the question
   * form; `answer` is the text sent to the model.
   */
  chatMessageRunAnswer(
    id: MessageRun["id"],
    answer: string,
    answers?: FollowupAnswer[],
  ): Promise<void>

  chatSettingsUpdate(chatId: Chat["id"], settings: ChatSettings): Promise<Chat>
  chatTitleUpdate(chatId: Chat["id"], title: string): Promise<Chat>

  /**
   * Returns a text file generated by the model via the `generate_file` tool.
   * The content lives outside the conversation history and is fetched on
   * demand when the user downloads the file from the chat.
   */
  generatedFileGet(fileId: GeneratedFile["id"]): Promise<GeneratedFile>

  /**
   * Clears the chat's step-by-step todo checklist (the `update_todo_list`
   * tool state bound to the chat).
   */
  chatTodoListClear(chatId: Chat["id"]): Promise<void>

  modelProviderTypeGet(): Promise<
    {
      type: Providers["type"]
      name: string
    }[]
  >
  modelProviderGet(): Promise<Providers[]>
  modelProviderCreate(
    modelProvider: Pick<Providers, "models" | "name" | "settings" | "type">,
  ): Promise<Providers>
  modelProviderUpdate(modelProvider: Providers): Promise<Providers>
  modelProviderDelete(id: Providers["id"]): Promise<void>
  modelProviderModelGet(
    providerId: Providers["id"],
  ): Promise<ModelProviderModel[]>
  /**
   * Connects to a (possibly unsaved) provider and lists its models, so a
   * provider can be tested before it is saved.
   */
  modelProviderCheck(provider: Providers): Promise<ModelProviderCheckResult>

  modelToolGet(): Promise<ModelTool[]>

  mcpServerGet(): Promise<McpServer[]>
  /**
   * Replaces the full list of MCP servers. Names must be unique and URLs must
   * be absolute http(s) URLs.
   */
  mcpServerUpdate(servers: McpServer[]): Promise<McpServer[]>
  /**
   * Connects to an MCP server and returns the tool definitions it exposes.
   * Throws when the server is unreachable or returns an error.
   */
  mcpServerToolsGet(server: McpServer): Promise<ModelTool[]>

  /** Built-in prompts followed by user prompts ordered by title. */
  promptGet(): Promise<Prompt[]>
  promptCreate(prompt: Pick<Prompt, "text" | "title">): Promise<Prompt>
  promptUpdate(prompt: Prompt): Promise<Prompt>
  promptDelete(id: Prompt["id"]): Promise<void>

  /**
   * Deletes every workspace with its chats, message runs and generated files,
   * then creates a new empty workspace and returns it. Providers, MCP servers,
   * prompts and settings are kept.
   */
  dataDeleteAll(): Promise<Workspace>
}

/**
 * Access to the browser pages the user is viewing (open tabs and the current
 * text selection). Only available where the client runs inside a browser
 * extension.
 */
export interface PageContextApi {
  pageContentGet(): Promise<Pick<PageContent, "id" | "title" | "url">[]>
  pageContentGetById(id: PageContent["id"]): Promise<null | PageContent>
  pageContentSelectionGet(): Promise<null | PageContentSelection>
}

/**
 * The api used by the UI. {@link PageContextApi} is only provided where the UI
 * runs inside a browser extension.
 */
export type ApiClient = ApiNotificationSource &
  BackendApi &
  Partial<PageContextApi>
